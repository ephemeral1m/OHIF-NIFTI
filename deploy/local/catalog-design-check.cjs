const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require('C:/Users/maczm/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 1.25 });
  page.setDefaultTimeout(90000);
  const result = { errors: [], checks: [] };
  page.on('pageerror', e => result.errors.push(e.message));
  const screenshot = async name => { console.log(name); await page.screenshot({ path: `local-data/acceptance/catalog-${name}.png`, animations: 'disabled' }); };
  try {
    await page.goto('http://127.0.0.1:1026/nifti?manifestId=6e5562936d5746d7bc95c55a9c5e7fe0');
    await page.locator('.catalog-table tbody tr').first().waitFor();
    await page.getByRole('img', { name: 'OHIF-AI-Experimental', exact: true }).waitFor();
    assert.equal(await page.locator('.catalog-table tbody tr').count(), 5);
    await screenshot('manifest');
    await page.getByRole('textbox', { name: '搜索清单病例' }).fill('13249');
    assert.equal(await page.locator('.catalog-table tbody tr').count(), 1);
    await page.locator('.catalog-files summary').click();
    assert(await page.locator('.catalog-files[open]').count());
    await page.getByRole('textbox', { name: '搜索清单病例' }).fill('no-such-case');
    await page.getByRole('heading', { name: '没有匹配的病例' }).waitFor();
    await page.getByRole('textbox', { name: '搜索清单病例' }).fill('');
    result.checks.push('manifest counts, search and file details');
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('menuitem', { name: '导入默认设置' }).click();
    await page.getByRole('combobox', { name: '原图类型' }).selectOption('MR');
    await page.waitForFunction(() => getComputedStyle(document.querySelector('[role="dialog"]')).opacity === '1');
    result.dialogBackground = await page.locator('[role="dialog"]').evaluate(el => getComputedStyle(el).backgroundColor);
    assert.notEqual(result.dialogBackground, 'rgba(0, 0, 0, 0)');
    await screenshot('settings');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '导入 CSV / JSON', exact: true }).click();
    await page.getByRole('combobox', { name: '相对路径起点' }).waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '打开本地原图', exact: true }).click();
    await page.getByRole('button', { name: '选择 NIfTI 文件', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    result.checks.push('settings, local and manifest dialogs');
    await page.getByRole('tab', { name: '已保存病例', exact: true }).click();
    await page.locator('.catalog-table tbody tr').first().waitFor();
    await screenshot('library');
    await page.getByRole('button', { name: '刷新已保存病例' }).click();
    result.checks.push('stored library and refresh');
    await page.getByRole('link', { name: 'DICOM 检查', exact: true }).click();
    await page.locator('[data-cy="study-list-results"] tr[data-cy]').first().waitFor();
    await screenshot('dicom');
    await page.locator('[data-cy="study-list-results"] tr[data-cy]').last().click();
    await page.locator('[data-cy^="mode-viewer-"]').waitFor();
    await screenshot('dicom-expanded');
    const dicomLink = await page.locator('a').filter({ has: page.locator('[data-cy^="mode-viewer-"]') }).getAttribute('href');
    result.dicomText = (await page.locator('.dicom-catalog-content').innerText()).slice(0, 1000);
    await page.locator('[data-cy="input-patientName"]').fill('NoSuchPatientForThemeCheck');
    await page.waitForTimeout(1500);
    await page.locator('[data-cy="input-patientName"]').fill('');
    await page.locator('[data-cy="study-list-results"] tr[data-cy]').first().waitFor();
    result.checks.push('DICOM study list and patient filter');
    await page.getByRole('link', { name: 'NIfTI 检查列表', exact: true }).click();
    await page.getByRole('tab', { name: '清单病例', exact: true }).click();
    await page.setViewportSize({ width: 800, height: 900 });
    await screenshot('narrow');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'only table scrolls horizontally');
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.getByRole('button', { name: '打开 train_13249_b_2.nii.gz', exact: true }).click();
    await page.waitForFunction(() => window.services?.segmentationService.getSegmentations().length === 6);
    await page.getByRole('img', { name: 'OHIF-AI-Experimental', exact: true }).waitFor();
    await screenshot('viewer');
    assert.equal(await page.locator('.experimental-brand svg').count(), 0);
    const brand = await page.locator('.experimental-brand').boundingBox();
    assert(brand.height < 30, 'wordmark stays on one line');
    assert.equal(await page.locator('.experimental-edition').innerText(), 'Experimental');
    result.checks.push('NIfTI open, masks and viewer brand sizing');
    await page.goto(`http://127.0.0.1:1026${dicomLink.startsWith('/') ? '' : '/'}${dicomLink}`);
    await page.waitForFunction(() => { try { const s = window.services; return !!s?.cornerstoneViewportService.getCornerstoneViewport(s.viewportGridService.getActiveViewportId())?.getCornerstoneImage?.(); } catch { return false; } });
    await page.getByRole('img', { name: 'OHIF-AI-Experimental', exact: true }).waitFor();
    await screenshot('dicom-viewer');
    result.checks.push('DICOM sequence expansion and viewer rendering');
    assert.deepEqual(result.errors, []); result.passed = true;
  } finally {
    result.finalPage = await page.evaluate(() => ({ url: location.href, text: document.body.innerText.slice(0, 1500) })).catch(() => null);
    fs.writeFileSync('local-data/acceptance/catalog-design.json', JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
    await browser.close();
  }
})();
